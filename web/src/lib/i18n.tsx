type Vars = Record<string, string | number>
type Ctx = {
  locale: Locale
  setLocale: (l: Locale) => void
  toggle: () => void
  t: (key: string, vars?: Vars) => string
}

const I18nContext = createContext<Ctx | null>(null)
const STORAGE_KEY = 'saig_locale'

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>(() => {
    try { return localStorage.getItem(STORAGE_KEY) === 'en' ? 'en' : 'zh' } catch { return 'zh' }
  })
  useEffect(() => {
    try { localStorage.setItem(STORAGE_KEY, locale) } catch { /* private mode */ }
    document.documentElement.lang = locale === 'zh' ? 'zh-CN' : 'en'
  }, [locale])
  const value = useMemo<Ctx>(() => {
    const t = (key: string, vars?: Vars) => {
      let text = locale === 'en' ? (en[key] ?? key) : key
      if (vars) for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v))
      return text
    }
    return { locale, setLocale, toggle: () => setLocale(l => l === 'zh' ? 'en' : 'zh'), t }
  }, [locale])
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): Ctx {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error('useI18n must be used within I18nProvider')
  return ctx
}

// 顶栏语言切换：中文界面显示 EN，英文界面显示「中文」。
export function LocaleToggle() {
  const { locale, toggle } = useI18n()
  return <button
    className="rounded-md px-2 py-1.5 text-sm hover:bg-[var(--muted)] cursor-pointer"
    title={locale === 'zh' ? 'Switch to English' : '切换到中文'}
    onClick={toggle}
  >{locale === 'zh' ? 'EN' : '中文'}</button>
}
